export function getLendingPoolAddress(): `0x${string}` {
  const addr = CONTRACT_ADDRESSES.LENDING_POOL;
  if (addr === "0x0") throw new Error("NEXT_PUBLIC_LENDING_POOL not set in .env.local");
  return addr;
}

